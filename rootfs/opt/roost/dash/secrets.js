'use strict';
// Keys & secrets for the tooling: SSH keys (for cloning and pushing over SSH) and
// named secrets that agents get as environment variables (optionally also used as
// git-over-HTTPS credentials for a host).
//
// Everything lives in roost's persisted home directory, readable only by the roost
// user. Values are write-only through the dashboard API: it never returns them.
// Note that anything an agent can use, it can also read. Prefer narrowly scoped tokens.
//
//   ~/.config/roost/vault.json        the source of truth (values + metadata)
//   ~/.config/roost/secrets.env       generated: `export NAME='value'` for shells and tmux
//   ~/.config/roost/git-credentials   generated: git credential store for HTTPS tokens
//   ~/.ssh/roost/<name>[.pub]         SSH keys
//   ~/.ssh/config                     a roost-managed block mapping hosts to keys
//   ~/.claude/CLAUDE.md, ~/.codex/AGENTS.md   a managed block listing what's available (no values)

const fs = require('fs');
const path = require('path');
const os = require('os');
const crypto = require('crypto');
const { execFile } = require('child_process');

const HOME = process.env.HOME || '/config/home';
const DIR = path.join(HOME, '.config', 'roost');
const VAULT = path.join(DIR, 'vault.json');
const ENV_FILE = path.join(DIR, 'secrets.env');
const GIT_CREDS = path.join(DIR, 'git-credentials');
const SSH_DIR = path.join(HOME, '.ssh');
const KEY_DIR = path.join(SSH_DIR, 'roost');
const SSH_CONFIG = path.join(SSH_DIR, 'config');
const AGENT_FILES = [path.join(HOME, '.claude', 'CLAUDE.md'), path.join(HOME, '.codex', 'AGENTS.md')];

const ENV_NAME = /^[A-Za-z_][A-Za-z0-9_]{0,63}$/;
const KEY_NAME = /^[A-Za-z0-9][A-Za-z0-9._-]{0,40}$/;
const HOST = /^[A-Za-z0-9.-]{1,253}(:[0-9]{1,5})?$/;
const MAX_VALUE = 64 * 1024;

// Names that change how the agents themselves sign in. Allowed, but flagged in the UI.
const CAUTION = {
  ANTHROPIC_API_KEY: 'Claude Code will bill this API key instead of your subscription, and Remote Control stops working.',
  ANTHROPIC_AUTH_TOKEN: 'Claude Code will use this token instead of your Claude login.',
  CLAUDE_CODE_OAUTH_TOKEN: 'Claude Code will use this token instead of your Claude login.',
  OPENAI_API_KEY: 'Codex may use this API key (API billing) instead of your ChatGPT login.',
  CODEX_API_KEY: 'Codex may use this API key instead of your ChatGPT login.',
  HOME: 'Overriding HOME breaks every tool in roost.',
  PATH: 'Overriding PATH breaks every tool in roost.',
};

const err = (status, message) => Object.assign(new Error(message), { status });

function run(cmd, args, opts = {}) {
  return new Promise((resolve) => {
    execFile(cmd, args, { timeout: 20000, maxBuffer: 1 << 20, ...opts }, (e, stdout, stderr) => {
      resolve({ code: e ? (typeof e.code === 'number' ? e.code : 1) : 0, out: String(stdout), err: String(stderr) });
    });
  });
}

function writePrivate(file, text) {
  fs.mkdirSync(path.dirname(file), { recursive: true, mode: 0o700 });
  const tmp = `${file}.${process.pid}.${crypto.randomBytes(3).toString('hex')}.tmp`;
  fs.writeFileSync(tmp, text, { mode: 0o600 });
  fs.renameSync(tmp, file);
  fs.chmodSync(file, 0o600);
}

// ------------------------------------------------------------------ vault
function load() {
  try {
    const v = JSON.parse(fs.readFileSync(VAULT, 'utf8'));
    return { version: 1, env: {}, keys: {}, ...v };
  } catch {
    return { version: 1, env: {}, keys: {} };
  }
}

function save(v) {
  writePrivate(VAULT, JSON.stringify(v, null, 2) + '\n');
  regenerate(v);
}

// Environment for processes roost starts (live chats). Shells read secrets.env instead.
function env() {
  const out = {};
  for (const [name, s] of Object.entries(load().env)) out[name] = s.value;
  return out;
}

// ------------------------------------------------------------------ generated files
const shQuote = (s) => `'${String(s).replace(/'/g, `'\\''`)}'`;

function regenerate(v = load()) {
  // Shell environment
  const lines = ['# Generated by roost from vault.json; edit secrets in the roost dashboard.'];
  for (const [name, s] of Object.entries(v.env)) lines.push(`export ${name}=${shQuote(s.value)}`);
  writePrivate(ENV_FILE, lines.join('\n') + '\n');

  // git over HTTPS
  const creds = Object.entries(v.env)
    .filter(([, s]) => s.gitHost)
    .map(([, s]) => `https://${encodeURIComponent(s.gitUser || 'oauth2')}:${encodeURIComponent(s.value)}@${s.gitHost}`);
  writePrivate(GIT_CREDS, creds.join('\n') + (creds.length ? '\n' : ''));
  ensureGitHelper();

  writeSshConfig(v);
  writeAgentNotes(v);
}

let gitHelperChecked = false;
async function ensureGitHelper() {
  if (gitHelperChecked) return;
  gitHelperChecked = true;
  const want = `store --file=${GIT_CREDS}`;
  const r = await run('git', ['config', '--global', '--get-all', 'credential.helper']);
  if (!r.out.split('\n').includes(want)) await run('git', ['config', '--global', '--add', 'credential.helper', want]);
}

const BLOCK_START = '# >>> roost managed: SSH keys (edit in the roost dashboard) >>>';
const BLOCK_END = '# <<< roost managed <<<';

function replaceBlock(text, start, end, block) {
  const i = text.indexOf(start);
  const j = text.indexOf(end);
  if (i !== -1 && j !== -1 && j > i) text = text.slice(0, i) + text.slice(j + end.length).replace(/^\n/, '');
  if (!block) return text.replace(/\n{3,}/g, '\n\n');
  return block + '\n' + (text.startsWith('\n') ? text : (text ? '\n' + text : ''));
}

function writeSshConfig(v) {
  const keys = Object.entries(v.keys);
  let block = '';
  if (keys.length) {
    const out = [BLOCK_START];
    const anyHost = [];
    for (const [name, k] of keys) {
      const file = path.join(KEY_DIR, name);
      if (!k.hosts || !k.hosts.length) { anyHost.push(file); continue; }
      for (const host of k.hosts) {
        const [h, port] = host.split(':');
        out.push(`Host ${h}`, `  HostName ${h}`, ...(port ? [`  Port ${port}`] : []), `  IdentityFile ${file}`, '  IdentitiesOnly yes', '  StrictHostKeyChecking accept-new', '');
      }
    }
    if (anyHost.length) out.push('Host *', ...anyHost.map((f) => `  IdentityFile ${f}`), '  StrictHostKeyChecking accept-new', '');
    out.push(BLOCK_END);
    block = out.join('\n');
  }
  let current = '';
  try { current = fs.readFileSync(SSH_CONFIG, 'utf8'); } catch {}
  // roost's block goes first: ssh uses the first value it finds for each option.
  writePrivate(SSH_CONFIG, replaceBlock(current, BLOCK_START, BLOCK_END, block));
}

const NOTE_START = '<!-- roost:secrets:start (managed by roost; edit keys & secrets in the dashboard) -->';
const NOTE_END = '<!-- roost:secrets:end -->';

function writeAgentNotes(v) {
  const envs = Object.entries(v.env);
  const keys = Object.entries(v.keys);
  let block = '';
  if (envs.length || keys.length) {
    const out = [NOTE_START, '## Keys and secrets roost provides', ''];
    if (envs.length) {
      out.push('These environment variables are set for you (values deliberately not shown here):', '');
      for (const [name, s] of envs) out.push(`- \`${name}\`${s.description ? `: ${s.description}` : ''}${s.gitHost ? ` (also used for git over HTTPS to ${s.gitHost})` : ''}`);
      out.push('');
    }
    if (keys.length) {
      out.push('SSH keys are configured in `~/.ssh/config`, so `git clone git@<host>:...` works for:', '');
      for (const [name, k] of keys) out.push(`- ${k.hosts && k.hosts.length ? k.hosts.join(', ') : 'any host'} (key \`${name}\`)`);
      out.push('');
    }
    out.push('Never print, log, commit or send these values anywhere they weren\'t meant to go. If one is missing or rejected, ask the user to add or fix it in roost\'s Secrets page.', NOTE_END);
    block = out.join('\n');
  }
  for (const file of AGENT_FILES) {
    let text = '';
    try { text = fs.readFileSync(file, 'utf8'); } catch { if (!block) continue; }
    const i = text.indexOf(NOTE_START);
    const j = text.indexOf(NOTE_END);
    if (i !== -1 && j > i) text = (text.slice(0, i) + text.slice(j + NOTE_END.length)).replace(/\n{3,}$/, '\n');
    if (block) text = text.replace(/\s*$/, '\n\n') + block + '\n';
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, text);
  }
}

// ------------------------------------------------------------------ listing
async function keyInfo(name, k) {
  const pubFile = path.join(KEY_DIR, name + '.pub');
  let publicKey = '';
  try { publicKey = fs.readFileSync(pubFile, 'utf8').trim(); } catch {}
  const fp = publicKey ? await run('ssh-keygen', ['-lf', pubFile]) : { out: '' };
  const [bits, fingerprint, , type] = fp.out.trim().split(/\s+/);
  return {
    name, hosts: k.hosts || [], comment: k.comment || '', created: k.created || null, imported: !!k.imported,
    publicKey, fingerprint: fingerprint || null, type: (type || '').replace(/[()]/g, '') || null, bits: Number(bits) || null,
    missing: !fs.existsSync(path.join(KEY_DIR, name)),
  };
}

async function list() {
  const v = load();
  const envs = Object.entries(v.env).map(([name, s]) => ({
    name, description: s.description || '', gitHost: s.gitHost || null, gitUser: s.gitUser || null,
    updated: s.updated || null, length: String(s.value || '').length, caution: CAUTION[name] || null,
  })).sort((a, b) => a.name.localeCompare(b.name));
  const keys = await Promise.all(Object.entries(v.keys).sort(([a], [b]) => a.localeCompare(b)).map(([n, k]) => keyInfo(n, k)));
  return { env: envs, keys, caution: CAUTION };
}

// ------------------------------------------------------------------ env secrets
function cleanHost(h) {
  if (h == null || h === '') return null;
  h = String(h).trim().replace(/^https?:\/\//, '').replace(/\/.*$/, '').toLowerCase();
  if (!HOST.test(h)) throw err(400, `"${h}" isn't a valid host name`);
  return h;
}

function setEnv(name, body) {
  if (!ENV_NAME.test(String(name))) throw err(400, 'Names use letters, digits and underscores, and can\'t start with a digit (e.g. GH_TOKEN).');
  const v = load();
  const prev = v.env[name];
  const value = body.value != null && body.value !== '' ? String(body.value) : prev ? prev.value : null;
  if (value == null) throw err(400, 'A value is required.');
  if (value.length > MAX_VALUE) throw err(400, 'That value is too large (64 KB max).');
  v.env[name] = {
    value,
    description: String(body.description ?? (prev ? prev.description : '') ?? '').slice(0, 300),
    gitHost: body.gitHost !== undefined ? cleanHost(body.gitHost) : prev ? prev.gitHost || null : null,
    gitUser: body.gitUser !== undefined ? (String(body.gitUser || '').trim().slice(0, 100) || null) : prev ? prev.gitUser || null : null,
    updated: new Date().toISOString(),
  };
  save(v);
  return { name, caution: CAUTION[name] || null };
}

function deleteEnv(name) {
  const v = load();
  if (!v.env[name]) throw err(404, 'No such secret');
  delete v.env[name];
  save(v);
}

// ------------------------------------------------------------------ SSH keys
function cleanHosts(hosts) {
  return [...new Set((Array.isArray(hosts) ? hosts : String(hosts || '').split(/[\s,]+/)).map(cleanHost).filter(Boolean))];
}

async function generateKey(name, body) {
  if (!KEY_NAME.test(String(name))) throw err(400, 'Key names use letters, digits, dots, dashes and underscores.');
  const v = load();
  if (v.keys[name]) throw err(409, `A key called "${name}" already exists`);
  fs.mkdirSync(KEY_DIR, { recursive: true, mode: 0o700 });
  const file = path.join(KEY_DIR, name);
  const comment = String(body.comment || `roost-${name}@${os.hostname()}`).slice(0, 100);
  const r = await run('ssh-keygen', ['-q', '-t', 'ed25519', '-N', '', '-C', comment, '-f', file]);
  if (r.code !== 0) throw err(500, 'ssh-keygen failed: ' + (r.err || r.out).trim());
  v.keys[name] = { hosts: cleanHosts(body.hosts), comment, created: new Date().toISOString() };
  save(v);
  return keyInfo(name, v.keys[name]);
}

async function importKey(name, body) {
  if (!KEY_NAME.test(String(name))) throw err(400, 'Key names use letters, digits, dots, dashes and underscores.');
  const v = load();
  if (v.keys[name]) throw err(409, `A key called "${name}" already exists`);
  let pem = String(body.privateKey || '').replace(/\r\n/g, '\n').trim() + '\n';
  if (!/-----BEGIN [A-Z ]*PRIVATE KEY-----/.test(pem)) throw err(400, 'Paste the private key, including the -----BEGIN … PRIVATE KEY----- line.');
  fs.mkdirSync(KEY_DIR, { recursive: true, mode: 0o700 });
  const file = path.join(KEY_DIR, name);
  const tmp = `${file}.import.${crypto.randomBytes(3).toString('hex')}`;
  writePrivate(tmp, pem);
  try {
    // Agents can't type passphrases, so store the key without one.
    if (body.passphrase) {
      const p = await run('ssh-keygen', ['-p', '-q', '-P', String(body.passphrase), '-N', '', '-f', tmp]);
      if (p.code !== 0) throw err(400, 'Couldn\'t unlock the key with that passphrase.');
    }
    const pub = await run('ssh-keygen', ['-y', '-P', '', '-f', tmp]);
    if (pub.code !== 0) throw err(400, /incorrect passphrase|passphrase/i.test(pub.err) ? 'This key has a passphrase: enter it so roost can store an unlocked copy.' : 'That doesn\'t look like a valid private key.');
    fs.renameSync(tmp, file);
    writePrivate(file + '.pub', pub.out.trim() + (body.comment ? ' ' + String(body.comment).slice(0, 100) : '') + '\n');
    fs.chmodSync(file + '.pub', 0o644);
  } finally {
    try { fs.unlinkSync(tmp); } catch {}
  }
  v.keys[name] = { hosts: cleanHosts(body.hosts), comment: String(body.comment || '').slice(0, 100), created: new Date().toISOString(), imported: true };
  save(v);
  return keyInfo(name, v.keys[name]);
}

function updateKey(name, body) {
  const v = load();
  if (!v.keys[name]) throw err(404, 'No such key');
  if (body.hosts !== undefined) v.keys[name].hosts = cleanHosts(body.hosts);
  save(v);
  return keyInfo(name, v.keys[name]);
}

function deleteKey(name) {
  const v = load();
  if (!v.keys[name]) throw err(404, 'No such key');
  delete v.keys[name];
  for (const f of [name, name + '.pub']) { try { fs.unlinkSync(path.join(KEY_DIR, f)); } catch {} }
  save(v);
}

// Try the key against a git host the way git would (ssh -T git@host).
async function testKey(name, host) {
  const v = load();
  const k = v.keys[name];
  if (!k) throw err(404, 'No such key');
  host = cleanHost(host || (k.hosts && k.hosts[0]) || 'github.com');
  const [h, port] = host.split(':');
  const args = ['-T', '-o', 'BatchMode=yes', '-o', 'ConnectTimeout=10', '-o', 'StrictHostKeyChecking=accept-new',
    '-o', 'IdentitiesOnly=yes', '-i', path.join(KEY_DIR, name), ...(port ? ['-p', port] : []), `git@${h}`];
  const r = await run('ssh', args, { timeout: 25000 });
  const output = (r.err + r.out).replace(/^Warning: Permanently added.*\n?/gm, '').trim();
  const ok = /successfully authenticated|welcome to gitlab|logged in as|authenticated via/i.test(output);
  return { host, ok, output: output.slice(0, 2000) || `ssh exited with ${r.code}` };
}

// At start-up, rebuild the generated files from the vault (if there is one).
function regenerateIfPresent() {
  if (fs.existsSync(VAULT)) regenerate();
}

module.exports = { list, env, regenerate, regenerateIfPresent, setEnv, deleteEnv, generateKey, importKey, updateKey, deleteKey, testKey, ENV_FILE };
